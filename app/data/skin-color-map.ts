export function vonLuschanToFitzpatrick(vls: number): number {
  if (vls <= 5) return 1;
  if (vls <= 10) return 2;
  if (vls <= 15) return 3;
  if (vls <= 21) return 4;
  if (vls <= 28) return 5;
  return 6;
}